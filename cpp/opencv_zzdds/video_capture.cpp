/*
 * video_capture.cpp
 *
 * Captures video frames from a V4L2 camera and publishes them on the
 * "ovidds_frames" DDS topic using the zzdds C++ bindings.
 *
 * Ported from the OpenDDS version.  The main structural differences are:
 *
 *  - Participant creation: TheParticipantFactoryWithArgs()    →  generated DDS::DomainParticipantFactory
 *  - TypeSupport: FrameTypeSupportImpl::register_type()       →  ovidds::FrameTypeSupport::register_type()
 *  - Entity creation (topic/pub/dw): via C ABI (C++ create_* also works; nullptr QoS uses defaults)
 *  - Listener base: LocalObject<DDS::DataWriterListener>      →  DDS::DataWriterListenerBase
 *  - Data field: frame.data.length(n) / .length()             →  frame.data.resize(n) / .size()
 *  - Primitive types: CORBA::Long                             →  int32_t
 *
 * Note on entity creation: create_topic / create_publisher / create_datawriter have
 * field-by-field QoS adaptation generated by zidl (both in- and out-direction, D3).
 * We still call them via the C ABI with nullptr QoS for simplicity; default QoS works
 * fine for the demo.  get_qos / set_qos are now fully implemented via D3.
 *
 * No camera / no display in CI: if the real camera fails to open (or
 * OVIDDS_MOCK_CAMERA is set), this falls back to a synthetic frame source
 * (a cycling solid color plus a frame-number overlay, not real video) instead
 * of exiting -- enough to exercise the full DDS write path deterministically
 * without hardware. OVIDDS_RUN_SECONDS bounds the run for CI instead of
 * waiting on an interactive stdin line.
 */

